// The weight of objects in AD&D is given in pounds rather than the basis
// standard of grams.  The a_poundage attribute should be set with
// any objects used within the AD&D framework.  When a_poundage is set,
// the a_weight attribute will be set with the (rounded off) equivalent
// in grams.
#define a_poundage 630
