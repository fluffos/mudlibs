// position.h
//
// This file defines possible values of the a_worn_at attribute
// defined in attrs/object.h.
// Also the values for wear_primary_hand to wear_waist index the array
// in a_carry_at defined for characters.
#define wear_primary_hand // For stuff held in primary hand (weapons).
#define wear_secondary_hand // Stuff held in secondary hand (shields).
#define wear_head 3 // For helmets, crowns, etc.
#define wear_feet 4 // For boots, shoes, etc.
#define wear_body 5 // For armor and clothing.
#define wear_gloves 6 // For gauntlets or gloves.
#define wear_neck 7 // For necklaces and the like.
#define wear_waist 8 // For belts and the like.
#define wear_left_hand 9 // Can only be held in left hand.
#define wear_right_hand 10 // Can only be held in right hand (e.g. golf club).
#define wear_finger 11 // For rings.
#define wear_foot 12 // For anything worn on only one foot.
#define wear_hand 13 // Stuff held in any hand (e.g. wands, rods, etc.).
#define wear_hands 14 // Held in two hands (e.g. 2-handed swords).
