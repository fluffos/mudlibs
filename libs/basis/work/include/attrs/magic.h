// Magic permeates the AD&D world, and gives it it's flavor.
// Magic is also the hardest thing to set down in terms that a
// computer can understand, for it is not logical, whereas a computer
// is the epitome of logic.  This file will set down some of
// the characteristics of magic as best as possible within the AD&D
// framework.
//
// One of the easiest of translations from the AD&D game to computer
// is that of the magical bonus.  Many items, especially weapons
// and armor have their magical abilities described as a numerical
// bonus.  Thus, a weapon with a magical bonus of +1, gives the
// wielder a better chance to attack, in this case, 1 is added to
// the attackers die roll.  The a_magical_bonus gives this number.
// Note that it can be negative (cursed items).
#define a_magical_bonus 690
