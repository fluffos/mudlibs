	string name1,name2;
	int index1,index2,index3;

	index1=random(sizeof(first_name));
	index2=random(sizeof(second_name1)); 
	name1=first_name[index1]["name"];
	name2=second_name1[index2]["name"];
	id1=first_name[index1]["id"];
	id2=second_name1[index2]["id"];

